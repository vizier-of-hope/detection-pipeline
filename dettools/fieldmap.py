"""Generate docs/siem/field-mappings.md from the actual processing pipelines.

Run: python -m dettools.fieldmap            (rewrites the doc)
     python -m dettools.fieldmap --check    (exit 1 if the doc is stale; used by tests)

For every (logsource, Sigma field, target) it compiles a one-field probe rule and reads the
field name the pipeline mapped it to. The result is generated, not hand-maintained, so it
cannot drift from what the converters really emit.
"""

from __future__ import annotations

import argparse
import copy
import sys

from sigma.rule import SigmaRule

from dettools.common import REPO_ROOT
from dettools.targets import TARGETS, backend_for, join_queries

DOC = REPO_ROOT / "docs" / "siem" / "field-mappings.md"
PROBE = "zzprobe"

# logsource -> Sigma fields worth knowing for that telemetry
LOGSOURCES: dict[str, tuple[dict, list[str]]] = {
    "process_creation (windows)": (
        {"category": "process_creation", "product": "windows"},
        ["Image", "OriginalFileName", "CommandLine", "ParentImage", "ParentCommandLine", "User",
         "CurrentDirectory", "IntegrityLevel", "Hashes", "ProcessId", "ParentProcessId"],
    ),
    "network_connection (windows)": (
        {"category": "network_connection", "product": "windows"},
        ["Image", "DestinationIp", "DestinationPort", "DestinationHostname", "SourceIp", "SourcePort", "User"],
    ),
    "file_event (windows)": (
        {"category": "file_event", "product": "windows"},
        ["Image", "TargetFilename", "User"],
    ),
    "registry_set (windows)": (
        {"category": "registry_set", "product": "windows"},
        ["Image", "TargetObject", "Details", "EventType"],
    ),
    "image_load (windows)": (
        {"category": "image_load", "product": "windows"},
        ["Image", "ImageLoaded", "Signed", "Hashes"],
    ),
    "dns_query (windows)": (
        {"category": "dns_query", "product": "windows"},
        ["Image", "QueryName"],
    ),
    "ps_script (windows)": (
        {"category": "ps_script", "product": "windows"},
        ["ScriptBlockText"],
    ),
    "security (windows service)": (
        {"service": "security", "product": "windows"},
        ["EventID", "TargetUserName", "SubjectUserName", "LogonType", "IpAddress", "WorkstationName"],
    ),
    "process_creation (linux)": (
        {"category": "process_creation", "product": "linux"},
        ["Image", "CommandLine", "ParentImage", "User"],
    ),
}


def _probe(logsource: dict, field: str) -> SigmaRule:
    return SigmaRule.from_dict({
        "title": "field probe",
        "logsource": logsource,
        "detection": {"sel": {f"{field}|contains": PROBE}, "condition": "sel"},
    })


def _leaf_items(detection):
    for item in getattr(detection, "detection_items", []):
        if hasattr(item, "detection_items"):
            yield from _leaf_items(item)
        else:
            yield item


def mapped_fields(target_key: str, logsource: dict, field: str) -> tuple[list[str] | None, str]:
    """Return (mapped field names, compiled query) or (None, error)."""
    target = TARGETS[target_key]
    rule = copy.deepcopy(_probe(logsource, field))
    try:
        queries = backend_for(target_key).convert_rule(rule, target.output_format)
        query = join_queries([target.postprocess(q) for q in queries] if target.postprocess else queries)
    except Exception as exc:  # pySigma raises many specific error types
        return None, " ".join(str(exc).split())
    names = []
    for detection in rule.detection.detections.values():
        for item in _leaf_items(detection):
            if any(PROBE in str(v) for v in item.value) and item.field and item.field not in names:
                names.append(item.field.removeprefix("$event1."))
    return names, query


def render() -> str:
    keys = list(TARGETS)
    out = [
        "# Sigma field mappings per SIEM target",
        "",
        "<!-- GENERATED by `python -m dettools.fieldmap`. Do not edit by hand. -->",
        "",
        "Generated from the pinned pySigma pipelines (see `dettools/targets.py`). `—` means the",
        "pipeline rejects the field (or the whole logsource) for that target, so a rule using it",
        "will be a coverage gap there. Pick fields that every SIEM you deploy to supports.",
        "",
        "Targets: " + ", ".join(f"`{k}` = {TARGETS[k].siem} {TARGETS[k].language}" for k in keys),
        "",
    ]
    for title, (logsource, fields) in LOGSOURCES.items():
        out += [f"## {title}", "", "| Sigma field | " + " | ".join(keys) + " |", "|---|" + "---|" * len(keys)]
        scope: dict[str, str] = {}
        for field in fields:
            cells = []
            for key in keys:
                names, query = mapped_fields(key, logsource, field)
                cells.append(", ".join(f"`{n}`" for n in names) if names else "—")
                if names and key not in scope:
                    scope[key] = query
            out.append(f"| `{field}` | " + " | ".join(cells) + " |")
        out += ["", "<details><summary>Data-source scoping each target adds (probe query)</summary>", ""]
        for key in keys:
            q = scope.get(key)
            if not q:
                out.append(f"- `{key}`: not supported for this logsource")
            elif key == "secops_yaral":
                out.append(f"- `{key}`: YARA-L rule wrapper around the `secops_udm` predicate")
            else:
                out.append(f"- `{key}`: `{' '.join(q.split())[:400]}`")
        out += ["", "</details>", ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = DOC.read_text(encoding="utf-8") if DOC.exists() else ""
        if current != text:
            print(f"{DOC.relative_to(REPO_ROOT)} is stale: run python -m dettools.fieldmap")
            return 1
        return 0
    DOC.parent.mkdir(parents=True, exist_ok=True)
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"Wrote {DOC.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
